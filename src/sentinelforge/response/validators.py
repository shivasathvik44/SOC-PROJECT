def validate_action_type(value: object) -> str:
    """Check an action type against the known vocabulary."""
    from .models import ActionType

    if not isinstance(value, str) or not ActionType.is_valid(value):
        raise ValidationError(
            f"unknown action type {value!r} (known: {', '.join(ActionType.ALL)})",
            "action_type",
        )
    return value


def validate_incident_id(value: object, allow_none: bool = True) -> str | None:
    """Check an incident id against the Phase 3 id format."""
    if value in (None, ""):
        if allow_none:
            return None
        raise ValidationError("an incident id is required", "incident_id")
    if not isinstance(value, str) or not INCIDENT_ID_PATTERN.match(value):
        raise ValidationError(f"not a valid incident id: {value!r}", "incident_id")
    return value


def validate_reason(value: object, required: bool = False) -> str:
    """Bound and clean the operator's free-text justification.

    Control characters are removed because this string is written to a database
    and rendered in a terminal; it is never interpreted.
    """
    if value in (None, ""):
        if required:
            raise ValidationError("a reason is required for this action", "reason")
        return ""
    if not isinstance(value, str):
        raise ValidationError(f"reason must be text, got {type(value).__name__}", "reason")
    cleaned = "".join(ch for ch in value if ch == " " or ch.isprintable()).strip()
    if required and not cleaned:
        raise ValidationError("a reason is required for this action", "reason")
    return cleaned[:MAX_REASON]


def validate_actor(value: object, field: str = "requested_by") -> str:
    """Check an operator label (who asked for this, who approved it)."""
    if value in (None, ""):
        return default_actor()
    if not isinstance(value, str):
        raise ValidationError(f"{field} must be text", field)
    text = value.strip()
    if len(text) > MAX_ACTOR or not ACTOR_PATTERN.match(text):
        raise ValidationError(
            f"{field} must be a short operator name "
            "(letters, digits, dot, dash, underscore, @ or space)",
            field,
        )
    return text


def default_actor() -> str:
    """The local operator's name, used when a caller does not supply one."""
    for source in (os.environ.get("SUDO_USER"), os.environ.get("USER")):
        if source and ACTOR_PATTERN.match(source):
            return source
    try:
        import pwd

        return pwd.getpwuid(os.getuid()).pw_name
    except Exception:  # pragma: no cover - no passwd database
        return "unknown"


def validate_ttl(value: object, allow_none: bool = True) -> int | None:
    """Check a containment lifetime in seconds."""
    if value in (None, ""):
        if allow_none:
            return None
        raise ValidationError("a TTL is required for this action", "ttl")
    if isinstance(value, bool):
        raise ValidationError("ttl must be a number of seconds", "ttl")
    if isinstance(value, str):
        text = value.strip()
        if not text.isdigit():
            raise ValidationError(f"ttl must be a whole number of seconds, got {text!r}", "ttl")
        value = int(text)
    if not isinstance(value, int):
        raise ValidationError("ttl must be a whole number of seconds", "ttl")
    if value < MIN_TTL:
        raise ValidationError(f"ttl must be at least {MIN_TTL} seconds", "ttl")
    if value > MAX_TTL:
        raise ValidationError(f"ttl must be at most {MAX_TTL} seconds ({MAX_TTL // 3600}h)", "ttl")
    return value


def validate_action_id(value: object) -> str:
    """Check an action id against the format this phase generates."""
    if not isinstance(value, str) or not re.match(r"^ACTION-\d{1,12}$", value):
        raise ValidationError(f"not a valid action id: {value!r}", "action_id")
    return value
