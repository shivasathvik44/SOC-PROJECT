@api.get("/mitre")
def mitre():
    """ATT&CK techniques seen across stored incidents.

    Mappings come from the detection rules (Phase 2's validated catalogue).
    The dashboard aggregates; it never invents a technique.
    """
    incident_id = request.args.get("incident_id")
    if incident_id:
        incident, failure = _get_incident(incident_id)
        if failure:
            return failure
        incidents_list = [incident]
    else:
        try:
            incidents_list = _load_incidents()
        except sqlite3.Error as exc:
            return error(503, "store_unavailable", f"cannot read the incident store: {exc}")
    items = mitre_breakdown(incidents_list)
    return jsonify(
        {
            "items": items,
            "total": len(items),
            "incident_count": len(incidents_list),
            "api_version": API_VERSION,
        }
    )


