"""Read-only JSON API for the dashboard (Phase 6).

Every endpoint here is a **GET**.  There is no route that changes an incident,
runs a scan, calls a provider, or touches the host: the dashboard is for
visibility and investigation, and a read-only API is the cheapest way to
guarantee that.  (It also means there is no state-changing endpoint to protect
against CSRF -- the safest kind of protection there is.)

Responses are built by :mod:`sentinelforge.dashboard.serializers`, so no
internal Python object is ever exposed and the wire format stays stable.  List
endpoints are always paginated and always bounded.
"""

from __future__ import annotations

import logging
import re
import sqlite3

from flask import Blueprint, current_app, jsonify, request

from ..models.event import Severity, parse_timestamp
from ..models.incident import IncidentStatus
