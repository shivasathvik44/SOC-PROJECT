@api.get("/health")
def health():
    """Liveness plus a short self-description.  Never exposes a secret."""
    ctx = context()
    database_ok = True
    incident_total = 0
    try:
        with ctx.store() as store:
            incident_total = store.count()
    except sqlite3.Error as exc:
        database_ok = False
        LOGGER.warning("health check could not read the incident store: %s", exc)
    return jsonify(
        {
            "status": "ok" if database_ok else "degraded",
            "api_version": API_VERSION,
            "demo": ctx.config.demo,
            "database": {
                "path": ctx.config.resolved_db_path(),
                "readable": database_ok,
                "incidents": incident_total,
            },
            "live": {
                "subscribers": ctx.bus.subscriber_count,
                "published": ctx.bus.published,
            },
            "monitors": ctx.monitors.describe() if ctx.monitors else [],
        }
    )


@api.get("/stats")
def stats():
    """Overview counters: incidents by severity and status, plus live rates."""
    ctx = context()
    try:
        with ctx.store() as store:
            severity_counts = store.severity_counts()
            status_counts = store.status_counts()
            total = store.count()
    except sqlite3.Error as exc:
        return error(503, "store_unavailable", f"cannot read the incident store: {exc}")
    return jsonify(
        serialize_stats(
            severity_counts, status_counts, ctx.live.snapshot(), total, demo=ctx.config.demo
        )
    )


